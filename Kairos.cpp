/**
 * @file Kairos.cpp
 * @brief MIDI clock master/slave and trigger generator for Daisy Patch
 * @version 1.0
 *
 * Outputs:
 *   OUT1-3   Bastl Kompass style trigger channels, density from CTRL1-3
 *   OUT4     16th note clock
 *   GATE OUT Reset pulse at the start of every 32 step pattern
 *   GATE IN1 Analog clock in, one pulse per step
 *   GATE IN2 Reset in
 *   CV1/CV2  Two independent 32 step Turing machine sequences
 *
 * Clock:
 *   A clock patched into GATE IN 1 takes priority; MIDI clock is next and is
 *   forwarded to MIDI out. Without either the internal clock runs: the encoder
 *   sets tempo and pressing it starts/stops the sequencer. All three sources
 *   send 24 PPQN clock and transport to MIDI out.
 */

#include "kairos.h"

// ============================================================================
// AUDIO CALLBACK
// ============================================================================

/**
 * @brief Runs at the audio sample rate and drives the trigger outputs
 *
 * Also generates the internal clock pulses. The pulses themselves are only
 * counted here; the main loop consumes them so that MIDI sending and DAC
 * writes stay out of the audio callback.
 */
void AudioCallback(AudioHandle::InputBuffer  in,
                   AudioHandle::OutputBuffer out,
                   size_t                    size)
{
    static float pulsePhase = 0.0f;

    // A gate clock edge realigns the generator so the MIDI clock bytes it fills
    // in between two edges are evenly spaced from the edge
    if(pulsePhaseReset)
    {
        pulsePhase      = 0.0f;
        pulsePhaseReset = false;
    }

    for(size_t i = 0; i < size; i++)
    {
        // Internal clock pulse generation
        if(!externalClockMode && isRunning)
        {
            pulsePhase += 1.0f;
            if(pulsePhase >= samplesPerPulse)
            {
                pulsePhase -= samplesPerPulse;
                internalPulsesGenerated++;
            }
        }
        else
        {
            pulsePhase = 0.0f;
        }

        // Trigger pulse widths
        for(int c = 0; c < NUM_KOMPASS_CHANNELS; c++)
        {
            if(triggerOut[c])
            {
                triggerCounter[c]++;
                if(triggerCounter[c] >= TRIGGER_PULSE_SAMPLES)
                    triggerOut[c] = false;
            }
        }

        if(clockOut)
        {
            clockOutCounter++;
            if(clockOutCounter >= TRIGGER_PULSE_SAMPLES)
                clockOut = false;
        }

        if(resetOut)
        {
            resetOutCounter++;
            if(resetOutCounter >= RESET_PULSE_SAMPLES)
                resetOut = false;
        }

        // 5V trigger = 1.0f on the audio outputs
        out[0][i] = triggerOut[0] ? 1.0f : 0.0f;
        out[1][i] = triggerOut[1] ? 1.0f : 0.0f;
        out[2][i] = triggerOut[2] ? 1.0f : 0.0f;
        out[3][i] = clockOut ? 1.0f : 0.0f;
    }
}

// ============================================================================
// MAIN
// ============================================================================

int main(void)
{
    hw.Init();

    // Restores the tempo from the last session before anything uses it
    LoadSettings();

    UpdateSamplesPerPulse();
    InitPatterns();

    hw.display.Fill(false);
    hw.display.SetCursor(0, 0);
    hw.display.WriteString("Kairos", Font_7x10, true);
    hw.display.Update();

    hw.midi.StartReceive();
    hw.StartAdc();
    hw.StartAudio(AudioCallback);

    uint32_t       lastDisplayUpdate  = System::GetNow();
    uint32_t       lastControlUpdate  = System::GetNow();
    const uint32_t DISPLAY_UPDATE_RATE = 50;

    for(;;)
    {
        uint32_t now = System::GetNow();

        // Controls run at a fixed 1kHz: the CTRL4 gesture decay and the knob
        // smoothing both depend on a known tick rate
        if(now != lastControlUpdate)
        {
            ProcessControls();
            WriteCvOutputs();
            ProcessSettingsSave();
            lastControlUpdate = now;
        }

        // Gate inputs: analog clock and reset. Polled on every pass because the
        // edge detector only ever sees what it is shown.
        ProcessGateInputs();

        // MIDI input: clock, transport and song position
        hw.midi.Listen();
        while(hw.midi.HasEvents())
            HandleMidiMessage(hw.midi.PopEvent());

        CheckExternalClockTimeout();
        CheckGateClockTimeout();

        // Consume internal clock pulses generated by the audio callback. Under
        // a MIDI master they are discarded; under a patched clock they only
        // fill in the MIDI clock bytes between two gate edges, which advance
        // the steps themselves.
        while(internalPulsesConsumed != internalPulsesGenerated)
        {
            internalPulsesConsumed++;

            if(externalClockMode)
                continue;

            if(gateClockMode)
                FillGateClockPulse();
            else
                OnClockPulse(true);
        }

        // Gate out carries the pattern reset pulse. Written on every pass, not
        // on the control tick, so the reset never lands after the clock pulse
        // it is supposed to precede.
        dsy_gpio_write(&hw.gate_output, resetOut ? 1 : 0);

        if(now - lastDisplayUpdate > DISPLAY_UPDATE_RATE)
        {
            UpdateDisplay();
            lastDisplayUpdate = now;
        }
    }
}
